#!/usr/bin/env node
// @ts-check
// Pins ACP's own schema (HarnessV3-ACP AC0-2): reads `schema/schema.json` from an installed @agentclientprotocol/sdk
// and writes src/adapters/agents/acp/schema-pin.js, the table the update reader checks against. Nothing is
// downloaded: by default it reads the SDK that the installed claude-agent-acp carries.
//   npm run acp-schema [-- --from <the sdk folder>]
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "adapters", "agents", "acp", "schema-pin.js");
/** Where the SDK sits among the global packages: claude-agent-acp carries it. */
const SDK_UNDER_AGENT = join("@agentclientprotocol", "claude-agent-acp", "node_modules", "@agentclientprotocol", "sdk");

/** The folder of the SDK to read: `--from`, else the one the global claude-agent-acp carries. @param {string[]} argv */
export function sdkFolder(argv = process.argv.slice(2)) {
  const i = argv.indexOf("--from");
  if (i >= 0 && argv[i + 1]) return resolve(argv[i + 1]);
  return join(execSync("npm root -g", { encoding: "utf8", windowsHide: true }).trim(), SDK_UNDER_AGENT);
}

/**
 * The pin from a parsed schema: each `session/update` kind with the fields it requires and their JSON types, the
 * kinds the schema marks unstable, and the capability fields `initialize` answers with.
 * @param {any} schema @param {string} version
 */
export function pinOf(schema, version) {
  const defs = schema.$defs || {};
  /** @param {any} node @returns {any} */
  const deref = (node) => (node?.$ref ? deref(defs[String(node.$ref).replace("#/$defs/", "")]) : node);
  /** @param {any} node @returns {string} */
  const typeOf = (node) => {
    const n = deref(node);
    if (!n) return "any";
    /** @param {string} t */
    const json = (t) => (t === "integer" ? "number" : t);
    if (typeof n.type === "string") return json(n.type);
    if (Array.isArray(n.type)) return n.type.filter((/** @type {string} */ t) => t !== "null").map(json).join("|");
    const alts = n.oneOf || n.anyOf;
    if (Array.isArray(alts)) return [...new Set(alts.map(typeOf))].filter((t) => t !== "null").join("|") || "any";
    // A property is often its definition wrapped in `allOf`, to carry a description of its own.
    if (Array.isArray(n.allOf)) return n.allOf.map(typeOf).find((/** @type {string} */ t) => t !== "any") || "any";
    return n.properties ? "object" : "any";
  };
  /** The required fields and the properties of a variant, its own and those it takes from `allOf`. @param {any} node */
  const shape = (node) => {
    const n = deref(node) || {};
    const parts = [n, ...(Array.isArray(n.allOf) ? n.allOf.map(deref) : [])];
    const props = Object.assign({}, ...parts.map((p) => p?.properties || {}));
    /** @type {string[]} */
    const required = [...new Set(parts.flatMap((p) => p?.required || []))];
    return { props, required };
  };
  const variants = defs.SessionUpdate?.oneOf || defs.SessionUpdate?.anyOf || [];
  /** @type {Record<string, Record<string, string>>} */
  const updates = {};
  /** The kinds the schema itself marks **UNSTABLE**: not part of the spec yet. @type {string[]} */
  const unstable = [];
  for (const v of variants) {
    const { props, required } = shape(v);
    const kind = props.sessionUpdate?.const;
    if (!kind) continue;
    updates[kind] = Object.fromEntries(required.filter((f) => f !== "sessionUpdate").map((f) => [f, typeOf(props[f])]));
    if (/\*\*UNSTABLE\*\*/.test(String(v.description || ""))) unstable.push(kind);
  }
  /** @param {string} name */
  const fields = (name) => Object.keys(deref(defs[name])?.properties || {}).filter((k) => k !== "_meta");
  return {
    sdk: version,
    updates,
    unstable,
    agentCapabilities: fields("AgentCapabilities"),
    sessionCapabilities: fields("SessionCapabilities"),
  };
}

/** The module text for a pin. @param {ReturnType<typeof pinOf>} pin */
const moduleOf = (pin) =>
  `// @ts-check\n// Generated by \`npm run acp-schema\` from @agentclientprotocol/sdk ${pin.sdk} (schema/schema.json): ACP's own\n// schema, pinned (HarnessV3-ACP AC0-2). Regenerate it; never edit it by hand.\n\nexport const ACP_SCHEMA = ${JSON.stringify(pin, null, 2)};\n`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = sdkFolder();
  const file = join(dir, "schema", "schema.json");
  if (!existsSync(file)) {
    console.error(`no ACP schema at ${file}: install claude-agent-acp, or pass --from <the sdk folder>`);
    process.exit(1);
  }
  const version = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version;
  const pin = pinOf(JSON.parse(readFileSync(file, "utf8")), version);
  writeFileSync(OUT, moduleOf(pin));
  console.log(`pinned ACP schema ${version}: ${Object.keys(pin.updates).length} update kinds -> ${OUT}`);
}
