#!/usr/bin/env node
// @ts-check
// Pins Codex's app-server protocol (HarnessV3-ACP AC2-1): runs the installed Codex's own `codex app-server
// generate-json-schema` (the stable API: no `--experimental`) into a folder of its own, and writes
// src/adapters/agents/codex/schema-pin.js — the methods each side sends, the items a thread holds, and what a thread
// and a turn take — which Codex's profile and the tests read. Nothing is downloaded: it reads the Codex installed here.
//   npm run codex-schema [-- --from <a folder generate-json-schema wrote>]
import { execSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "adapters", "agents", "codex", "schema-pin.js");
/** The bundle with every definition of the protocol's second version, the one Filament speaks. */
const BUNDLE = "codex_app_server_protocol.v2.schemas.json";

/** The methods a union of messages carries. @param {any} union @returns {string[]} */
const methodsOf = (union) => (union?.oneOf || union?.anyOf || []).map((/** @type {any} */ v) => v?.properties?.method?.enum?.[0]).filter(Boolean);

/**
 * The pin from a folder `generate-json-schema` wrote: what each side sends, the items a thread holds, and the fields
 * `thread/start`, `thread/resume`, `thread/fork` and `turn/start` take.
 * @param {string} dir @param {string} version
 */
export function pinOf(dir, version) {
  /** @param {string} f */
  const read = (f) => JSON.parse(readFileSync(join(dir, f), "utf8"));
  const defs = read(BUNDLE).definitions || {};
  /** @param {string} name */
  const fields = (name) => Object.keys(defs[name]?.properties || {}).sort();
  return {
    codex: version,
    requests: methodsOf(read("ClientRequest.json")).sort(),
    serverRequests: methodsOf(read("ServerRequest.json")).sort(),
    notifications: methodsOf(read("ServerNotification.json")).sort(),
    items: /** @type {string[]} */ ((defs.ThreadItem?.oneOf || []).map((/** @type {any} */ v) => v?.properties?.type?.enum?.[0]).filter(Boolean)),
    threadStart: fields("ThreadStartParams"),
    threadResume: fields("ThreadResumeParams"),
    threadFork: fields("ThreadForkParams"),
    turnStart: fields("TurnStartParams"),
  };
}

/** The module text for a pin. @param {ReturnType<typeof pinOf>} pin */
const moduleOf = (pin) =>
  `// @ts-check\n// Generated by \`npm run codex-schema\` from Codex ${pin.codex} (\`codex app-server generate-json-schema\`, the stable\n// API): Codex's app-server protocol, pinned (HarnessV3-ACP AC2-1). Regenerate it; never edit it by hand.\n\nexport const CODEX_SCHEMA = ${JSON.stringify(pin, null, 2)};\n`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf("--from");
  const version = /\d+\.\d+\.\d+\S*/.exec(execSync("codex --version", { encoding: "utf8", windowsHide: true }))?.[0] || "?";
  const from = i >= 0 && argv[i + 1] ? resolve(argv[i + 1]) : null;
  const dir = from || mkdtempSync(join(tmpdir(), "filament-codex-schema-"));
  try {
    if (!from) execSync(`codex app-server generate-json-schema --out "${dir}"`, { stdio: "ignore", windowsHide: true });
    const pin = pinOf(dir, version);
    writeFileSync(OUT, moduleOf(pin));
    console.log(`pinned Codex ${version}: ${pin.requests.length} requests, ${pin.notifications.length} notifications, ${pin.items.length} item kinds -> ${OUT}`);
  } finally {
    if (!from) rmSync(dir, { recursive: true, force: true });
  }
}
